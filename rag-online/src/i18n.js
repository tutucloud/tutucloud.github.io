const SUPPORTED = Object.keys(DICTS);

function detectLang() {
  const saved = localStorage.getItem('rag-lang');
  if (saved && DICTS[saved]) return saved;
  const nav = (navigator.language || 'en').toLowerCase();
  if (nav.startsWith('zh')) return 'zh-CN';
  const base = nav.split('-')[0];
  return SUPPORTED.find(l => l.toLowerCase().startsWith(base)) || 'en';
}

let lang = detectLang();

export function getLang() { return lang; }

export function setLang(l) {
  if (!DICTS[l]) return;
  lang = l;
  localStorage.setItem('rag-lang', l);
  document.documentElement.lang = l;
}

export function supportedLangs() {
  return SUPPORTED.map(l => ({ code: l, name: DICTS[l].lang_name }));
}

export function t(key, params) {
  let s = DICTS[lang][key] ?? DICTS['en'][key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split('{' + k + '}').join(String(v));
    }
  }
  return s;
}

// 将静态文案写入所有带 data-i18n / data-i18n-placeholder 的元素
export function applyStatic() {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}
